// The characters every site font is subset to: Google Fonts' "latin" subset plus arrows (→ is common in links),
// plus whatever site.fontExtraText adds. check-glyphs.mjs warns if a built page uses anything outside this set.
const RANGES = [[0x20, 0x7e], [0xa0, 0xff], [0x131, 0x131], [0x152, 0x153], [0x2bb, 0x2bc], [0x2c6, 0x2c6], [0x2da, 0x2da],
  [0x2dc, 0x2dc], [0x304, 0x304], [0x308, 0x308], [0x329, 0x329], [0x2000, 0x206f], [0x20ac, 0x20ac], [0x2122, 0x2122],
  [0x2190, 0x2199], [0x2212, 0x2212], [0x2215, 0x2215], [0xfeff, 0xfeff], [0xfffd, 0xfffd]];
export function subsetText(extra = "") {
  let s = "";
  for (const [a, b] of RANGES) for (let c = a; c <= b; c++) s += String.fromCodePoint(c);
  return s + extra;
}
