// node scripts/fonts.mjs  (runs before eleventy: "build": "node scripts/fonts.mjs && eleventy && node scripts/check-glyphs.mjs")
// For each font in site.fonts: subset src/fonts-src/<file> (originals, never modified) to the Latin set as WOFF2 in
// src/fonts/, and write src/css/fonts.css with
//   - the real @font-face rules (URLs carry a content hash, so immutable caching is safe), and
//   - a metric-matched local fallback per family ("<Family> Fallback": size-adjust + ascent/descent/line-gap overrides,
//     computed from the font file the way Capsize/fontaine do), so text doesn't jump when the web font arrives.
// Also writes src/_data/fontAssets.json ({file: url}) for the <link rel="preload"> tags in head.njk.
// Use in CSS: font-family: "IBM Plex Sans", "IBM Plex Sans Fallback", sans-serif;
import fs from "node:fs"; import { createHash } from "node:crypto";
import subsetFont from "subset-font"; import { fromBuffer } from "@capsizecss/unpack";
import site from "../src/_data/site.js"; import { subsetText } from "./font-ranges.mjs";

const text = subsetText(site.fontExtraText || ""), pct = (x) => (x * 100).toFixed(2) + "%";
fs.mkdirSync("src/fonts", { recursive: true }); fs.mkdirSync("src/css", { recursive: true });
let css = "/* GENERATED by scripts/fonts.mjs from site.fonts: do not edit. */\n", assets = {}, fallbacks = new Map();
for (const f of site.fonts || []) {
  const src = fs.readFileSync(`src/fonts-src/${f.file}`), out = await subsetFont(src, text, { targetFormat: "woff2" });
  const name = f.file.replace(/\.(ttf|otf|woff2?)$/i, ".woff2"); fs.writeFileSync(`src/fonts/${name}`, out);
  const url = `/fonts/${name}?v=${createHash("sha256").update(out).digest("hex").slice(0, 10)}`; assets[f.file] = url;
  console.log(`${f.file}: ${src.length} -> ${out.length} bytes`);
  css += `@font-face { font-family: "${f.family}"; src: url("${url}") format("woff2"); font-weight: ${f.weight || 400}; font-style: ${f.style || "normal"}; font-display: swap; }\n`;
  if (!fallbacks.has(f.family)) {
    const m = await fromBuffer(src), fb = (await import(`@capsizecss/metrics/${f.fallback || "arial"}`)).default;
    const sa = (m.xWidthAvg / m.unitsPerEm) / (fb.xWidthAvg / fb.unitsPerEm), em = m.unitsPerEm * sa;
    fallbacks.set(f.family, `@font-face { font-family: "${f.family} Fallback"; src: local("${fb.fullName}"), local("${fb.postscriptName}"); ` +
      `size-adjust: ${pct(sa)}; ascent-override: ${pct(m.ascent / em)}; descent-override: ${pct(Math.abs(m.descent) / em)}; line-gap-override: ${pct(m.lineGap / em)}; }\n`);
  }
}
css += [...fallbacks.values()].join("");
fs.writeFileSync("src/css/fonts.css", css); fs.writeFileSync("src/_data/fontAssets.json", JSON.stringify(assets, null, 2) + "\n");
